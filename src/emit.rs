//! Bend harness, C shim, and Rust wrappers.
//!
//! Bend 2.0 emits one C program and a `main` ([bendlang/bend#813](https://github.com/bendlang/bend/issues/813)).
//! Numeric defs often compile to static "spins" that nothing outside the
//! file can name, and a flat def's own segment is dropped when every call
//! was inlined. The harness below gives each selected def a non-flat host
//! segment (a `Nat` match with a non-tail self-call on the unused branch)
//! and mentions that segment twice from `main`, which is what keeps
//! `FID_bend_build_host_*` in the linked program. The fuel argument is
//! always `0`, so the self-call never runs. The shim then builds a task
//! node and calls `corpus_eval`, the same entry the emitted `main` uses.

use crate::parse::{NumTy, Signature};
use std::fmt::Write as _;

pub fn module_name(stem: &str) -> String {
    stem.replace('-', "_")
}

pub fn c_symbol(module: &str, def: &str) -> String {
    format!("bend_build_{module}_{}", rust_ident_body(def))
}

pub fn host_def(def: &str) -> String {
    format!("bend_build_host_{}", rust_ident_body(def))
}

fn rust_ident_body(def: &str) -> String {
    def.replace('.', "_")
}

pub fn rust_fn_name(def: &str) -> String {
    let body = rust_ident_body(def);
    if is_rust_keyword(&body) {
        format!("r#{body}")
    } else {
        body
    }
}

fn is_rust_keyword(name: &str) -> bool {
    matches!(
        name,
        "as" | "async"
            | "await"
            | "break"
            | "const"
            | "continue"
            | "crate"
            | "dyn"
            | "else"
            | "enum"
            | "extern"
            | "false"
            | "fn"
            | "for"
            | "if"
            | "impl"
            | "in"
            | "let"
            | "loop"
            | "match"
            | "mod"
            | "move"
            | "mut"
            | "pub"
            | "ref"
            | "return"
            | "self"
            | "Self"
            | "static"
            | "struct"
            | "super"
            | "trait"
            | "true"
            | "type"
            | "unsafe"
            | "use"
            | "where"
            | "while"
            | "abstract"
            | "become"
            | "box"
            | "do"
            | "final"
            | "macro"
            | "override"
            | "priv"
            | "typeof"
            | "unsized"
            | "virtual"
            | "yield"
            | "try"
            | "gen"
    )
}

pub fn harness(import_path: &str, exports: &[&Signature]) -> String {
    let mut out = String::new();
    let _ = writeln!(
        out,
        "# Generated by bend-build. The host defs exist so selected Bend\n\
         # definitions stay as callable C segments. See bend-build's README.\n\
         import Base\n\
         import {import_path} as BendBuildMod\n",
        import_path = import_path,
    );
    for sig in exports {
        let host = host_def(&sig.name);
        let params: Vec<String> = sig
            .params
            .iter()
            .enumerate()
            .map(|(i, ty)| format!("a{i}: {}", ty.bend_name()))
            .collect();
        let args: Vec<String> = (0..sig.params.len()).map(|i| format!("a{i}")).collect();
        let call_args = args.join(", ");
        let rec_args = if args.is_empty() {
            "p".to_string()
        } else {
            format!("p, {call_args}")
        };
        let host_params = if params.is_empty() {
            "k: Nat".to_string()
        } else {
            format!("k: Nat, {}", params.join(", "))
        };
        let _ = writeln!(
            out,
            r#"def {host}({host_params}) -> {ret}:
  match k:
    case 0n:
      BendBuildMod.{name}({call_args})
    case 1n+p:
      r = {host}({rec_args})
      r
"#,
            ret = sig.ret.bend_name(),
            name = sig.name,
        );
    }
    out.push_str("def main() -> Nat:\n");
    let mut nat_vars = Vec::new();
    for (n, sig) in exports.iter().enumerate() {
        for (sample_i, sample) in [0, 1].into_iter().enumerate() {
            let var = format!("v{n}_{sample_i}");
            let args = sig
                .params
                .iter()
                .map(|ty| {
                    let (a, b) = ty.samples();
                    if sample == 0 {
                        a
                    } else {
                        b
                    }
                })
                .collect::<Vec<_>>();
            let arg_list = if args.is_empty() {
                "0n".to_string()
            } else {
                format!("0n, {}", args.join(", "))
            };
            let _ = writeln!(out, "  {var} = {}({arg_list})", host_def(&sig.name));
            nat_vars.push(sig.ret.as_nat(&var));
        }
    }
    let folded = nat_vars
        .into_iter()
        .reduce(|acc, next| format!("Nat.add({acc}, {next})"))
        .unwrap_or_else(|| "0n".to_string());
    let _ = writeln!(out, "  {folded}\n");
    out
}

pub fn fid_arity(c_src: &str, fid: &str) -> Option<usize> {
    let key = format!("#define {fid} ");
    let at = c_src.find(&key)?;
    let rest = &c_src[at + key.len()..];
    let index: usize = rest
        .chars()
        .take_while(|c| c.is_ascii_digit())
        .collect::<String>()
        .parse()
        .ok()?;
    let marker = "Fid FID_T[] = {";
    let table_at = c_src.find(marker)?;
    let table = &c_src[table_at + marker.len()..];
    let end = table.find("};")?;
    let entries = &table[..end];
    let entry = entries.split("},").nth(index)?.trim();
    let entry = entry.trim_start_matches('{').trim();
    let arity = entry.split(',').next()?.trim();
    arity.parse().ok()
}

/// Rename Bend's `main` and append one exported C function per def.
pub fn shim(
    c_src: &str,
    exports: &[&Signature],
    module: &str,
    threads: u32,
) -> Result<String, String> {
    const MAIN: &str = "int main(int argc, char** argv) {";
    if !c_src.contains(MAIN) {
        return Err(
            "generated C has no `int main(int argc, char** argv)`; this bend-build \
             release expects Bend 2.0's C shape"
                .to_string(),
        );
    }
    let mut out = c_src.replace(
        MAIN,
        "static int bend_build_unused_main(int argc, char** argv) {",
    );
    let end = out
        .rfind("#endif")
        .ok_or_else(|| "generated C does not end its host section with #endif".to_string())?;
    let mut extra = String::new();
    let _ = writeln!(
        extra,
        r#"
/* bend-build host ABI.
   Issue 813 tracks a real native library target. Until then each export is a
   Bend segment entered the way the runtime enters main: a task node plus
   corpus_eval. Runtime failures still _exit the process. Calls are not
   re-entrant; the generated Rust wrappers take a mutex. */
static u64* bend_build_heap;
static int bend_build_ready;

static void bend_build_init(void) {{
  if (!bend_build_ready) {{
    bend_build_heap = corpus_setup(false, {threads}, 0);
    io_stk = pool_stack();
    bend_build_ready = 1;
  }}
}}
"#,
        threads = threads,
    );
    for sig in exports {
        let host = host_def(&sig.name);
        let fid = format!("FID_{host}");
        let arity = fid_arity(&out, &fid).ok_or_else(|| {
            format!("generated C has no `{fid}`; the host segment was eliminated")
        })?;
        let expect = sig.params.len() + 1;
        if arity != expect {
            return Err(format!(
                "{fid} has arity {arity}, expected {expect} (fuel plus the Bend arguments)"
            ));
        }
        let c_name = c_symbol(module, &sig.name);
        let c_params: Vec<String> = (0..sig.params.len())
            .map(|i| format!("uint64_t a{i}"))
            .collect();
        let param_list = if c_params.is_empty() {
            "void".to_string()
        } else {
            c_params.join(", ")
        };
        let _ = writeln!(extra, "uint64_t {c_name}({param_list}) {{");
        let _ = writeln!(extra, "  bend_build_init();");
        let _ = writeln!(extra, "  Env e = {{ bend_build_heap, ALC[0] }};");
        let _ = writeln!(extra, "  u64 loc = task_node(e, {fid}, TERM_HOLE, 0, 0);");
        let _ = writeln!(extra, "  e.mem[loc + 0] = 0;");
        for i in 0..sig.params.len() {
            let _ = writeln!(extra, "  e.mem[loc + {}] = a{i};", i + 1);
        }
        let _ = writeln!(
            extra,
            "  return corpus_eval(bend_build_heap, term_tsk({fid}, loc));"
        );
        extra.push_str("}\n\n");
    }
    out.insert_str(end, &extra);
    Ok(out)
}

pub fn rust_module(module: &str, source: &str, exports: &[&Signature]) -> String {
    let mut body = String::new();
    let _ = writeln!(
        body,
        "// Generated by bend-build from `{source}`. Do not edit.\n\
         // Bindings call Bend segments linked into this crate. Numeric words are\n\
         // immediates: U32 and F32 are 32-bit patterns, Nat is an integer <= 2^48-1.\n\
         // A Nat outside that range panics here. A Bend runtime fault still exits\n\
         // the process. The functions share one Bend heap and must not run together,\n\
         // so each call takes the module lock.\n\
         \n\
         #![allow(dead_code)]\n\
         \n\
         use std::sync::Mutex;\n\
         \n\
         static BEND_BUILD_LOCK: Mutex<()> = Mutex::new(());\n\
         \n\
         fn bend_build_lock() -> std::sync::MutexGuard<'static, ()> {{\n\
             BEND_BUILD_LOCK.lock().unwrap_or_else(|err| err.into_inner())\n\
         }}\n\
         \n\
         const BEND_NAT_MAX: u64 = (1 << 48) - 1;\n\
         \n\
         fn bend_check_nat(value: u64) -> u64 {{\n\
             if value > BEND_NAT_MAX {{\n\
                 panic!(\"Bend Nat must be an immediate in 0..=2^48-1, got {{value}}\");\n\
             }}\n\
             value\n\
         }}\n\
         \n\
         fn bend_word_u32(word: u64) -> u32 {{\n\
             if word > u32::MAX as u64 {{\n\
                 panic!(\"Bend returned a U32/F32 word with high bits set: {{word:#x}}\");\n\
             }}\n\
             word as u32\n\
         }}\n\
         \n\
         #[link(name = \"bend_build_{module}\", kind = \"static\")]\n\
         #[link(name = \"pthread\")]\n\
         #[link(name = \"m\")]\n\
         extern \"C\" {{\n",
        source = source,
        module = module,
    );
    for sig in exports {
        let c_name = c_symbol(module, &sig.name);
        let params: Vec<String> = (0..sig.params.len())
            .map(|i| format!("a{i}: u64"))
            .collect();
        let _ = writeln!(body, "    fn {c_name}({}) -> u64;", params.join(", "));
    }
    body.push_str("}\n");
    for sig in exports {
        let rust_name = rust_fn_name(&sig.name);
        let c_name = c_symbol(module, &sig.name);
        let rust_params: Vec<String> = sig
            .params
            .iter()
            .enumerate()
            .map(|(i, ty)| format!("a{i}: {}", ty.rust_name()))
            .collect();
        let call_args: Vec<String> = sig
            .params
            .iter()
            .enumerate()
            .map(|(i, ty)| match ty {
                NumTy::U32 => format!("a{i} as u64"),
                NumTy::F32 => format!("a{i}.to_bits() as u64"),
                NumTy::Nat => format!("bend_check_nat(a{i})"),
            })
            .collect();
        let ret = match sig.ret {
            NumTy::U32 => "bend_word_u32(word)".to_string(),
            NumTy::F32 => "f32::from_bits(bend_word_u32(word))".to_string(),
            NumTy::Nat => "bend_check_nat(word)".to_string(),
        };
        let _ = writeln!(
            body,
            r#"
/// Calls Bend def `{bend}`.
pub fn {rust_name}({params}) -> {rust_ret} {{
    let _guard = bend_build_lock();
    let word = unsafe {{ {c_name}({args}) }};
    {ret}
}}
"#,
            bend = sig.name,
            params = rust_params.join(", "),
            rust_ret = sig.ret.rust_name(),
            args = call_args.join(", "),
        );
    }
    format!("pub mod {module} {{\n{body}}}\n")
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::parse::{scan, select, NumTy};

    #[test]
    fn reads_segment_arity() {
        let src = "#define FID_bend_build_host_add 1\nCONSTV Fid FID_T[] = { { 1, 0, 0, 1 }, { 3, 0, 0, 1 } };\n";
        assert_eq!(fid_arity(src, "FID_bend_build_host_add"), Some(3));
    }

    #[test]
    fn harness_mentions_each_export_twice() {
        let items = scan("def add(a: U32, b: U32) -> U32:\n  a\n");
        let sigs = select(&items, None).unwrap();
        let text = harness("./m.bend", &sigs);
        assert_eq!(text.matches("bend_build_host_add(").count(), 4);
        assert!(text.contains("BendBuildMod.add(a0, a1)"));
        assert_eq!(sigs[0].ret, NumTy::U32);
    }
}
